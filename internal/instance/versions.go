package instance

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"webdock/internal/render"
)

func VersionStatePath(root string) string {
	return filepath.Join(root, "data", ".webdock-versions")
}

func VersionStateKey(name string) (string, bool) {
	spec, ok := findComponentSpec(name)
	if !ok || spec.dataVersionKey == "" {
		return "", false
	}
	return spec.dataVersionKey, true
}

func LoadVersionState(root string) (Values, error) {
	data, err := os.ReadFile(VersionStatePath(root))
	if err != nil {
		return nil, fmt.Errorf("read data version state: %w", err)
	}
	values, err := ParseEnv(data)
	if err != nil {
		return nil, fmt.Errorf("parse data version state: %w", err)
	}
	if err := validateVersionState(values); err != nil {
		return nil, err
	}
	return values, nil
}

func RenderVersionState(values Values) []byte {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)

	var b strings.Builder
	b.WriteString("# Generated by Webdock after successful component startup.\n")
	for _, key := range keys {
		fmt.Fprintf(&b, "%s=%s\n", key, values[key])
	}
	return []byte(b.String())
}

func WriteVersionState(root string, values Values) error {
	if err := validateVersionState(values); err != nil {
		return err
	}
	return render.WriteFile(VersionStatePath(root), RenderVersionState(values), 0o644)
}

func validateVersionState(values Values) error {
	for key, version := range values {
		if !isVersionStateKey(key) {
			return fmt.Errorf("data version state contains unknown component %q", key)
		}
		if !componentVersionPattern.MatchString(strings.TrimSpace(version)) {
			return fmt.Errorf("data version state has invalid %s version %q", key, version)
		}
	}
	return nil
}

func isVersionStateKey(key string) bool {
	for _, spec := range componentSpecs {
		if spec.dataVersionKey == key {
			return true
		}
	}
	return false
}
